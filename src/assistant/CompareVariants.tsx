/**
 * „Nebeneinander vergleichen“: the two versions of the proposal (Ideal und Kaufbar, #436) of one
 * room side by side, each as the 2D plan and as a 3D picture, with a button to take the one you
 * like. The 3D pictures are taken from the real 3D view one after the other (as the look before
 * handing over does), so the comparison opens a moment after the click.
 */
import { useEffect, useState } from 'react';
import type { CatalogItem } from '../catalog/types';
import { placedRooms } from '../design/apply/proposal';
import { roomPlanSvg } from '../design/render';
import type { FlatResult } from '../design/types';
import type { RoomType } from '../suggest/furnishing';
import { roomShots } from './roomShots';

export type VariantKey = 'ideal' | 'kaufbar';

export interface CompareProps {
  ideal: FlatResult;
  kaufbar: FlatResult;
  roomTypes: Record<string, RoomType>;
  /** Rooms that exist in the plan, by id. */
  rooms: { id: string; name: string }[];
  catalog: CatalogItem[];
  onTake: (v: VariantKey) => void;
  onClose: () => void;
}

const TITLE: Record<VariantKey, string> = { ideal: 'Ideal', kaufbar: 'Kaufbar' };
const SUB: Record<VariantKey, string> = {
  ideal: 'Claudes Plan mit Soll-Möbeln als Platzhalter',
  kaufbar: 'mit den gefundenen IKEA-/Möbelix-Produkten',
};

export function CompareVariants({ ideal, kaufbar, roomTypes, rooms, catalog, onTake, onClose }: CompareProps) {
  const placed = {
    ideal: placedRooms(ideal, roomTypes).filter((r) => rooms.some((x) => x.id === r.analysis.roomId)),
    kaufbar: placedRooms(kaufbar, roomTypes).filter((r) => rooms.some((x) => x.id === r.analysis.roomId)),
  };
  const ids = placed.kaufbar.map((r) => r.analysis.roomId);
  const [roomId, setRoomId] = useState(ids[0] ?? '');
  const [shots, setShots] = useState<Record<string, string | null>>({});
  const names = Object.fromEntries(rooms.map((r) => [r.id, r.name]));

  // one 3D picture per version and room, taken when the room is first shown
  useEffect(() => {
    let alive = true;
    for (const v of ['ideal', 'kaufbar'] as const) {
      const key = `${v}:${roomId}`;
      if (key in shots) continue;
      const room = placed[v].find((r) => r.analysis.roomId === roomId);
      if (!room?.program) {
        setShots((s) => ({ ...s, [key]: null }));
        continue;
      }
      setShots((s) => (key in s ? s : { ...s, [key]: '' }));
      void roomShots({ ...room, program: room.program }, catalog)
        .then((imgs) => alive && setShots((s) => ({ ...s, [key]: imgs?.[0] ? `data:${imgs[0].mediaType};base64,${imgs[0].data}` : null })))
        .catch(() => alive && setShots((s) => ({ ...s, [key]: null })));
    }
    return () => {
      alive = false;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [roomId]);

  return (
    <div className="modal-backdrop" onMouseDown={onClose}>
      <div className="modal compare-modal" role="dialog" aria-modal="true" aria-label="Vorschläge nebeneinander" data-testid="design-compare" onMouseDown={(e) => e.stopPropagation()} onKeyDown={(e) => e.key === 'Escape' && onClose()}>
        <header className="modal-head">
          <h2>Vorschläge nebeneinander</h2>
          <button onClick={onClose} aria-label="Schließen">
            ×
          </button>
        </header>
        <div className="modal-body">
          {ids.length > 1 && (
            <label className="field">
              <span className="field-label">Raum</span>
              <span className="field-input">
                <select value={roomId} onChange={(e) => setRoomId(e.target.value)} data-testid="design-compare-room">
                  {ids.map((id) => (
                    <option key={id} value={id}>
                      {names[id] || 'Raum ohne Namen'}
                    </option>
                  ))}
                </select>
              </span>
            </label>
          )}
          <div className="compare-grid">
            {(['ideal', 'kaufbar'] as const).map((v) => {
              const room = placed[v].find((r) => r.analysis.roomId === roomId);
              const result = v === 'ideal' ? ideal : kaufbar;
              const review = result.rooms.find((r) => r.roomId === roomId)?.review;
              const shot = shots[`${v}:${roomId}`];
              const count = room ? room.layout.items.length : 0;
              return (
                <section key={v} className="compare-col" data-testid={`design-compare-${v}`}>
                  <h3>{TITLE[v]}</h3>
                  <p className="muted small">{SUB[v]}</p>
                  {room ? (
                    <>
                      <div
                        className="compare-plan"
                        role="img"
                        aria-label={`Grundriss ${TITLE[v]}`}
                        // generated by roomPlanSvg from the plan itself (text is escaped there)
                        dangerouslySetInnerHTML={{ __html: roomPlanSvg({ analysis: room.analysis, layout: room.layout, program: room.program, roomNames: names, catalog }, { size: 520, legend: false }).svg }}
                      />
                      <div className="compare-3d">
                        {shot ? <img src={shot} alt={`3D-Ansicht ${TITLE[v]}`} /> : <p className="muted small">{shot === '' || shot === undefined ? '3D-Bild wird aufgenommen …' : '3D-Bild nicht möglich (3D-Ansicht zeigen).'}</p>}
                      </div>
                      <p className="small">
                        {count} Möbel{review ? ` · Begehung ${review.score} Punkte` : ''}
                      </p>
                    </>
                  ) : (
                    <p className="muted small">Für diesen Raum gibt es hier keinen Vorschlag.</p>
                  )}
                  <button className="primary" onClick={() => onTake(v)} data-testid={`design-compare-take-${v}`}>
                    Diesen übernehmen ({TITLE[v]})
                  </button>
                </section>
              );
            })}
          </div>
          <p className="muted small">Übernommen wird die ganze Fassung für alle Räume; mit Strg+Z in einem Schritt rückgängig.</p>
        </div>
      </div>
    </div>
  );
}
