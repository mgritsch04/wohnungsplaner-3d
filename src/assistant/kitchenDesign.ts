/**
 * The kitchen in Claude's furnishing proposal (#350): for a kitchen room Claude plans a kitchen
 * run (one or two rows of modules: base and tall cabinets, sink, dishwasher, oven, fridge, with
 * wall cabinets, hob and hood above) from the room's wall lengths, doors and windows. Claude only
 * names modules and their order; the app looks for the wall face where the row stands free
 * (`layoutKitchenRun`, same rules as the kitchen planner) and adds the countertop over the base
 * modules. Every module starts as a generic placeholder with a shop search term; the product
 * search can swap it for a real product (the module keeps its kitchen role and shape).
 */
import { z } from 'zod';
import { findCatalogItem, GENERIC_CATALOG } from '../catalog/generic';
import type { CatalogItem } from '../catalog/types';
import { COUNTERTOP_PRICE_PER_M, generateCountertops, layoutKitchenRun, usableFaceRange, wallFaceRange, type RunModule } from '../kitchen/kitchen';
import { derivePlan, type DerivedPlan } from '../model/derived';
import type { Furniture, PlanZone, Project } from '../model/schema';
import { add, closestPointOnSegment, dist, pointInPolygon, scale, type Vec2 } from '../model/vec';
import { isKeepFree, zoneLabels, zoneRoomId } from '../model/zones';
import { roomIdAt, type FurnishingSuggestion, type RoomSuggestion, type RoomType } from '../suggest/furnishing';

/** Kitchen modules Claude may use (the countertop is generated by the app). */
export const KITCHEN_MODULES: CatalogItem[] = GENERIC_CATALOG.filter((c) => c.kitchen && c.kitchen.type !== 'countertop');
/** Modules that sit above (or in) the floor module they belong to. */
const ABOVE = new Set(['wall', 'hood', 'cooktop']);
export const isAboveModule = (c: CatalogItem | undefined) => !!c?.kitchen && ABOVE.has(c.kitchen.type);
export const MAX_RUNS = 2;
export const MAX_SLOTS = 10;
const MAX_ABOVE = 3;
const MIN_WIDTH = 0.15;
const MAX_WIDTH = 1.2;
/** A module counts as inside the kitchen zone when its centre is at most this far outside (zones are drawn by hand). */
const ZONE_TOL = 0.25;
/** A further row joins the kitchen (L shape or opposite row) only when one of its modules is this close to the earlier rows (centre to centre). */
const MAX_ROW_GAP = 2.2;

export interface KitchenPart {
  /** Generic module id, or the id of a real product found for it. */
  catalogId: string;
  /** Generic module the part stands for (role, shape, typical size). */
  base: string;
  /** Width override in metres (generic modules only). */
  width?: number;
  /** Claude's description of the wanted product and the shop search term. */
  label: string;
  search: string;
}

export interface KitchenSlot extends KitchenPart {
  /** Wall cabinet, hob or hood above this floor module. */
  above: KitchenPart[];
}

export interface DesignKitchen {
  /** One row per wall (a second row makes an L or a two-row kitchen). */
  runs: KitchenSlot[][];
  frontColor: string;
  /** Claude's description of fronts and worktop (style, colour, material). */
  fronts: string;
  reason: string;
}

export interface KitchenFace {
  wallId: string;
  side: 1 | -1;
  length: number;
  /** Start of the usable part (from the start of the usable face): > 0 when a kitchen zone covers only part of the wall. */
  offset?: number;
  /** Label of the marked kitchen area (Z1 …) the face lies in. */
  zone?: string;
  /** Doors and windows on this face, from the start of the face (metres). */
  openings: { kind: 'door' | 'window' | 'passage'; from: number; to: number; sill: number }[];
}

const cm = (v: number) => Math.round(v * 100);
const clip = (v: unknown, max: number) => (typeof v === 'string' ? v.trim().replace(/\s+/g, ' ').slice(0, max) : '');

/** Marked area meant for the kitchen (#416): „Küche“, „Küchenzeile“, „Kochen“. */
export const isKitchenZone = (z: Pick<PlanZone, 'purpose'>) => /küche|kueche|koch|kitchen/i.test(z.purpose) && !/waschk/i.test(z.purpose) && !isKeepFree(z.purpose);

/** The kitchen zone of a room (the first one marked), if the user marked one. */
export function kitchenZoneOf(project: Project, roomId: string, derived: DerivedPlan = derivePlan(project)): PlanZone | undefined {
  return (project.zones ?? []).find((z) => isKitchenZone(z) && zoneRoomId(project, derived, z) === roomId);
}

const outlineDistance = (p: Vec2, poly: Vec2[]) => Math.min(...poly.map((a, i) => closestPointOnSegment(p, a, poly[(i + 1) % poly.length]).distance));
const inZone = (p: Vec2, z: PlanZone) => pointInPolygon(p, z.points) || outlineDistance(p, z.points) <= ZONE_TOL;

/**
 * Wall faces inside the room (the side of each room wall that faces the room), longest first.
 * With a kitchen zone (#416) only the part of each face inside the zone counts.
 */
export function kitchenFaces(project: Project, roomId: string, derived: DerivedPlan = derivePlan(project)): KitchenFace[] {
  const room = project.rooms.find((r) => r.id === roomId);
  const g = derived.rooms.get(roomId);
  if (!room || !g) return [];
  const zone = kitchenZoneOf(project, roomId, derived);
  const zoneKey = zone ? zoneLabels(project.zones ?? []).get(zone.id) : undefined;
  const nodes = new Set(room.nodeIds);
  const out: KitchenFace[] = [];
  for (const w of project.walls) {
    if (!nodes.has(w.a) || !nodes.has(w.b)) continue;
    const fp = derived.footprints.get(w.id);
    if (!fp) continue;
    for (const side of [1, -1] as const) {
      const face = wallFaceRange(fp, side);
      const mid = add(add(fp.a, scale(fp.dir, (face.s0 + face.s1) / 2)), scale(fp.normal, side * (fp.thickness / 2 + 0.3)));
      if (!pointInPolygon(mid, g.interior)) continue;
      const usable = usableFaceRange(derived, w.id, side);
      if (!usable) continue;
      // in a kitchen zone: the longest stretch of the face in front of which the zone lies
      let r = usable;
      if (zone) {
        const STEP = 0.05;
        let best: { s0: number; s1: number } | null = null;
        let from: number | null = null;
        for (let s = usable.s0; s <= usable.s1 + 1e-9; s += STEP) {
          const at = Math.min(s, usable.s1);
          // across the module depth (the zone may stop short of the wall), along the wall exactly to its end
          const inside = [0.05, 0.3, 0.55].some((d) => pointInPolygon(add(add(fp.a, scale(fp.dir, at)), scale(fp.normal, side * (fp.thickness / 2 + d))), zone.points));
          if (inside && from === null) from = at;
          const end = !inside || s + STEP > usable.s1 + 1e-9;
          if (end && from !== null) {
            const to = inside ? at : at - STEP;
            if (!best || to - from > best.s1 - best.s0) best = { s0: from, s1: to };
            from = null;
          }
        }
        if (!best) continue;
        r = best;
      }
      if (r.s1 - r.s0 < 0.6) continue;
      const openings = (derived.openings.get(w.id) ?? []).map((o) => ({
        kind: o.opening.kind,
        from: Math.max(0, Math.min(o.s0, o.s1) - r.s0),
        to: Math.min(r.s1 - r.s0, Math.max(o.s0, o.s1) - r.s0),
        sill: o.bottom,
      }));
      out.push({
        wallId: w.id,
        side,
        length: r.s1 - r.s0,
        ...(r.s0 > usable.s0 + 1e-9 ? { offset: r.s0 - usable.s0 } : {}),
        ...(zoneKey ? { zone: zoneKey } : {}),
        openings: openings.filter((o) => o.to > o.from),
      });
    }
  }
  return out.sort((a, b) => b.length - a.length);
}

/** True when the room already has kitchen modules (then no new kitchen is planned). */
export function hasKitchen(project: Project, roomId: string, derived: DerivedPlan = derivePlan(project)): boolean {
  return project.furniture.some((f) => f.kitchen && f.kitchen.type !== 'countertop' && roomIdAt(project, derived, f) === roomId);
}

/**
 * Rooms whose kitchen run Claude plans: at most one kitchen per flat. A room with a marked
 * kitchen zone wins, then a room the user set to „Küche“, then a room whose name says kitchen.
 * A flat that already has a kitchen run gets none – more than one kitchen only when the user set
 * several rooms to „Küche“ themselves.
 */
export function plannedKitchenRooms(
  project: Project,
  roomIds: string[],
  typeOf: (id: string) => RoomType,
  chosen: Record<string, RoomType>,
  derived: DerivedPlan = derivePlan(project),
): string[] {
  const free = (id: string) => !hasKitchen(project, id, derived) && kitchenFaces(project, id, derived).length > 0;
  const explicit = roomIds.filter((id) => chosen[id] === 'kitchen' && free(id));
  if (explicit.length > 1) return explicit;
  const anyKitchen = project.rooms.some((r) => hasKitchen(project, r.id, derived));
  if (anyKitchen) return explicit;
  const zoned = roomIds.find((id) => !!kitchenZoneOf(project, id, derived) && free(id));
  if (zoned) return [zoned];
  if (explicit.length) return explicit;
  const named = roomIds.find((id) => typeOf(id) === 'kitchen' && free(id));
  return named ? [named] : [];
}

const KIND: Record<string, string> = { door: 'Tür', window: 'Fenster', passage: 'Durchgang' };

/** Prompt part for a kitchen room: wall faces with doors/windows, the module list and the answer field. */
export function kitchenPromptPart(faces: KitchenFace[]): string[] {
  const wall = (f: KitchenFace, i: number) => {
    const ops = f.openings.map((o) => `${KIND[o.kind] ?? o.kind} ${cm(o.from)}–${cm(o.to)} cm${o.kind === 'window' ? ` (Brüstung ${cm(o.sill)} cm)` : ''}`);
    return `  Wand ${i + 1}: nutzbar ${cm(f.length)} cm${ops.length ? `; ${ops.join(', ')}` : '; frei'}`;
  };
  const zone = faces.find((f) => f.zone)?.zone;
  return [
    'Küche: In diesem Raum fehlt die Küchenzeile. Plane die Küchenzeile im Feld "kitchen" (NICHT in "items"):',
    ...(zone ? [`Die Küchenzeile gehört in den markierten Bereich ${zone}; die Wände unten sind nur der Teil in diesem Bereich.`] : []),
    'Wände der Küche (Länge der Wandfläche; Türen/Fenster mit Abstand vom Wandanfang):',
    ...faces.slice(0, 8).map(wall),
    'Küchenmodule (Format „id: Art, Breite×Tiefe×Höhe, Richtwert“):',
    ...KITCHEN_MODULES.map((c) => `${c.id}: ${c.name}, ${cm(c.width)}×${cm(c.depth)}×${cm(c.height)} cm${c.price ? `, Richtwert ${Math.round(c.price.amount)} €` : ''}`),
    `- "runs": 1 Zeile, oder ${MAX_RUNS} für L-Form/zweizeilig (Zeile 1 kommt an die längste passende Wand, Zeile 2 direkt anschließend über Eck oder gegenüber – nie an eine entfernte Wand). Je Zeile die Bodenmodule von links nach rechts, höchstens ${MAX_SLOTS}; Oberschrank, Kochfeld und Dunstabzug stehen in "above" des Bodenmoduls darunter (Kochfeld + Haube über dem Backofen- oder einem Unterschrank).`,
    '- Die Bodenmodule einer Zeile dürfen zusammen nicht länger als die Wand sein; Türen frei lassen, unter Fenstern nur Bodenmodule (keine Hoch- oder Oberschränke), Kühlschrank/Hochschrank an ein Zeilenende.',
    `- Breiten nur bei Unter-/Oberschränken anpassen ("width_cm" ${cm(MIN_WIDTH)}–${cm(MAX_WIDTH)}), um die Wand zu füllen. Arbeitsplatte erzeugt die App.`,
    '- Spüle, Geschirrspüler daneben, Kochfeld mit Abstand zur Spüle; zum Essen ggf. Tisch und Stühle in "items".',
    '- Je Modul "search" = kurzer Suchbegriff für den Shop (z. B. Serie, Front, Farbe); "fronts" = Fronten und Arbeitsplatte (Farbe, Material, Stil), "frontColor" = Hex-Farbe der Fronten.',
  ];
}

export const KITCHEN_JSON_HINT =
  '"kitchen":{"fronts":"…","frontColor":"#f2f0eb","reason":"…","runs":[[{"catalogId":"generic-k-tall-60","search":"…"},{"catalogId":"generic-k-oven","search":"…","above":[{"catalogId":"generic-k-cooktop","search":"…"},{"catalogId":"generic-k-hood-60","search":"…"}]}]]}';

const PartSchema = z.object({ catalogId: z.unknown(), width_cm: z.unknown().optional(), search: z.unknown().optional(), label: z.unknown().optional() });
const SlotSchema = PartSchema.extend({ above: z.array(PartSchema).optional().catch([]) });
const KitchenSchema = z.object({
  fronts: z.unknown().optional(),
  frontColor: z.unknown().optional(),
  reason: z.unknown().optional(),
  runs: z.array(z.array(SlotSchema).catch([])).catch([]),
});

/** Checks Claude's kitchen: only known modules, above-modules only in "above", widths clamped; null when no row is left. */
export function parseKitchen(raw: unknown): { kitchen: DesignKitchen | null; dropped: number } {
  const parsed = KitchenSchema.safeParse(raw);
  if (!parsed.success) return { kitchen: null, dropped: 0 };
  let dropped = 0;
  const part = (p: z.infer<typeof PartSchema>, above: boolean): KitchenPart | null => {
    const id = typeof p.catalogId === 'string' ? p.catalogId.trim() : '';
    const item = KITCHEN_MODULES.find((c) => c.id === id);
    if (!item || isAboveModule(item) !== above) {
      dropped++;
      return null;
    }
    const w = Number(p.width_cm) / 100;
    const sizable = item.kitchen!.type === 'base' || item.kitchen!.type === 'wall';
    return {
      catalogId: id,
      base: id,
      ...(sizable && Number.isFinite(w) && w > 0 ? { width: Math.max(MIN_WIDTH, Math.min(MAX_WIDTH, Math.round(w * 100) / 100)) } : {}),
      label: clip(p.label, 80) || clip(p.search, 80) || item.name,
      search: clip(p.search, 60) || item.name,
    };
  };
  const runs: KitchenSlot[][] = [];
  for (const r of parsed.data.runs.slice(0, MAX_RUNS)) {
    const run: KitchenSlot[] = [];
    for (const s of r.slice(0, MAX_SLOTS)) {
      const floor = part(s, false);
      if (!floor) continue;
      // a wall cabinet without own width follows a resized base cabinet below it
      const above = (s.above ?? [])
        .slice(0, MAX_ABOVE)
        .map((a) => part(a, true))
        .filter((a): a is KitchenPart => !!a)
        .map((a) => (floor.width && !a.width && findCatalogItem(a.base)?.kitchen?.type === 'wall' ? { ...a, width: floor.width } : a));
      run.push({ ...floor, above });
    }
    if (run.length) runs.push(run);
  }
  if (!runs.length) return { kitchen: null, dropped };
  const color = clip(parsed.data.frontColor, 7);
  return {
    kitchen: { runs, frontColor: /^#[0-9a-f]{6}$/i.test(color) ? color.toLowerCase() : '#f2f0eb', fronts: clip(parsed.data.fronts, 200), reason: clip(parsed.data.reason, 300) },
    dropped,
  };
}

/** All parts of a kitchen (floor modules and what sits above them). */
export const kitchenParts = (k: DesignKitchen): KitchenPart[] => k.runs.flatMap((run) => run.flatMap((s) => [s, ...s.above]));

/** Same module with the same search term = one product to look for. */
export const partKey = (p: Pick<KitchenPart, 'base' | 'search'>) => `${p.base}|${p.search.toLowerCase()}`;

/** Distinct parts with their count, in order of first appearance. */
export function kitchenShoppingList(k: DesignKitchen): { part: KitchenPart; key: string; count: number }[] {
  const out: { part: KitchenPart; key: string; count: number }[] = [];
  for (const p of kitchenParts(k)) {
    const key = partKey(p);
    const hit = out.find((x) => x.key === key);
    if (hit) hit.count++;
    else out.push({ part: p, key, count: 1 });
  }
  return out;
}

/** Every part with key `key` becomes the found product `catalogId` (no width override: the product has its own). */
export function setKitchenProduct(k: DesignKitchen, key: string, catalogId: string): DesignKitchen {
  const swap = <T extends KitchenPart>(p: T): T => (partKey(p) === key ? { ...p, catalogId, width: undefined } : p);
  return { ...k, runs: k.runs.map((run) => run.map((s) => ({ ...swap(s), above: s.above.map(swap) }))) };
}

export type Resolve = (catalogId: string) => CatalogItem | undefined;
export const resolveWith = (items: CatalogItem[]): Resolve => (id) => findCatalogItem(id) ?? items.find((c) => c.id === id);

/** Floor length of a row (what advances along the wall). */
export function runLength(run: KitchenSlot[], resolve: Resolve): number {
  return run.reduce((s, p) => s + (p.width ?? resolve(p.catalogId)?.width ?? 0.6), 0);
}

/** Guide price of the kitchen: modules (real prices for found products) plus the countertop over the floor modules. */
export function kitchenTotal(k: DesignKitchen, resolve: Resolve): { real: number; placeholder: number } {
  let real = 0;
  let placeholder = 0;
  for (const p of kitchenParts(k)) {
    const c = resolve(p.catalogId);
    if (!c?.price) continue;
    if (p.catalogId === p.base) placeholder += c.price.amount;
    else real += c.price.amount;
  }
  const worktop = k.runs.reduce((s, run) => s + run.filter((p) => resolve(p.catalogId)?.kitchen?.type !== 'tall' && resolve(p.catalogId)?.kitchen?.type !== 'fridge').reduce((a, p) => a + (p.width ?? resolve(p.catalogId)?.width ?? 0), 0), 0);
  return { real, placeholder: placeholder + Math.round(worktop * COUNTERTOP_PRICE_PER_M) };
}

const START_STEP = 0.1;
const MAX_STARTS = 40;

function modulesOf(run: KitchenSlot[], resolve: Resolve): RunModule[] {
  const out: RunModule[] = [];
  for (const s of run) {
    for (const p of [...s.above, s]) {
      const item = resolve(p.catalogId) ?? findCatalogItem(p.base);
      if (!item) continue;
      // a found product without kitchen role still stands in for its module
      const base = findCatalogItem(p.base);
      const withRole = item.kitchen || !base?.kitchen ? item : { ...item, kitchen: structuredClone(base.kitchen), elevation: item.elevation ?? base.elevation };
      out.push({ catalogId: p.catalogId, item: withRole, ...(p.width ? { width: p.width } : {}) });
    }
  }
  return out;
}

export interface PlacedKitchen {
  items: Furniture[];
  /** Names of modules that found no free place (one entry per module). */
  missing: string[];
}

/**
 * Places the rows of `kitchen` in room `roomId`: each row goes to the free wall face (and start
 * along it) where most of its modules stand free; the second row avoids the first and must join
 * it (over the corner or opposite), never at a distant wall. With a marked kitchen zone (#416)
 * every module stays inside it and the kitchen keeps out of the other marked areas. Modules that
 * do not fit anywhere are reported. The countertop is generated over the placed floor modules.
 * Nothing in `project` is changed.
 */
export function placeKitchen(project: Project, roomId: string, kitchen: DesignKitchen, resolve: Resolve): PlacedKitchen {
  const derived = derivePlan(project);
  const faces = kitchenFaces(project, roomId, derived);
  const zone = kitchenZoneOf(project, roomId, derived);
  const others = (project.zones ?? []).filter((z) => z.id !== zone?.id && zoneRoomId(project, derived, z) === roomId);
  const draft: Project = { ...project, furniture: [...project.furniture] };
  const items: Furniture[] = [];
  const missing: string[] = [];
  const used = new Set<string>();
  const fits = (f: Furniture) => insideRoom(project, derived, f, roomId) && (!zone || inZone(f, zone)) && !others.some((z) => pointInPolygon(f, z.points));
  for (const run of kitchen.runs) {
    const len = runLength(run, resolve);
    // Claude's order or its mirror image (e.g. the sink under the window instead of the hob)
    const orders = [modulesOf(run, resolve), modulesOf([...run].reverse(), resolve)];
    // a further row joins the rows placed so far (L shape or opposite row)
    const floor = items.filter((f) => f.kitchen && !ABOVE.has(f.kitchen.type));
    const joins = (slots: ReturnType<typeof layoutKitchenRun>['slots']) => !floor.length || slots.some((s) => floor.some((f) => dist(f, s.furniture) <= MAX_ROW_GAP));
    let best: { face: KitchenFace; slots: ReturnType<typeof layoutKitchenRun>['slots']; free: number } | null = null;
    const done = () => !!best && best.free === best.slots.length;
    for (const face of faces) {
      if (used.has(face.wallId)) continue;
      const room = Math.max(0, face.length - len);
      const steps = Math.min(MAX_STARTS, Math.floor(room / START_STEP));
      for (const modules of orders) {
        for (let i = 0; i <= steps && !done(); i++) {
          const start = (face.offset ?? 0) + (steps ? (room * i) / steps : 0);
          const { slots } = layoutKitchenRun(draft, { wallId: face.wallId, side: face.side, start, modules, frontColor: kitchen.frontColor }, derived);
          if (!joins(slots)) continue;
          const free = slots.filter((s) => !s.problem && fits(s.furniture)).length;
          if (!best || free > best.free) best = { face, slots, free };
        }
      }
      if (done()) break;
    }
    if (!best || !best.free) {
      missing.push(...orders[0].map((m) => m.item?.name ?? m.catalogId));
      continue;
    }
    used.add(best.face.wallId);
    for (const s of best.slots) {
      if (s.problem || !fits(s.furniture)) missing.push(s.name);
      else {
        items.push(s.furniture);
        draft.furniture.push(s.furniture);
      }
    }
  }
  if (items.length) {
    const temp: Project = { ...project, furniture: [...items], groups: [] };
    generateCountertops(temp);
    items.push(...temp.furniture.filter((f) => f.kitchen?.type === 'countertop'));
  }
  return { items, missing };
}

function insideRoom(project: Project, derived: DerivedPlan, f: Furniture, roomId: string): boolean {
  return roomIdAt(project, derived, f) === roomId;
}


/**
 * Preview with kitchens: the kitchen runs are placed first, then `furnish` places the other
 * furniture around them (it gets the project with the kitchen modules already standing in it).
 */
export function furnishWithKitchens(
  project: Project,
  kitchens: { roomId: string; roomName: string; type: RoomType; kitchen: DesignKitchen }[],
  resolve: Resolve,
  furnish: (draft: Project) => FurnishingSuggestion,
): FurnishingSuggestion {
  const placed = kitchens.map((k) => ({ ...k, ...placeKitchen(project, k.roomId, k.kitchen, resolve) }));
  const draft: Project = { ...project, furniture: [...project.furniture, ...placed.flatMap((k) => k.items)] };
  const s = furnish(draft);
  // the kitchen run belongs to the suggestion, too: a new preview of the room replaces it
  for (const k of placed) for (const f of k.items) f.suggested = true;
  const rooms: RoomSuggestion[] = s.rooms.map((r) => {
    const k = placed.find((x) => x.roomId === r.roomId);
    return k ? { ...r, placed: [...k.items, ...r.placed], missing: [...k.missing, ...r.missing] } : r;
  });
  for (const k of placed) if (!rooms.some((r) => r.roomId === k.roomId)) rooms.push({ roomId: k.roomId, roomName: k.roomName, type: k.type, placed: k.items, missing: k.missing });
  return { ...s, rooms, items: rooms.flatMap((r) => r.placed) };
}
